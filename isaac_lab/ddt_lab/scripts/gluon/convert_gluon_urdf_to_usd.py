#!/usr/bin/env python3
"""Convert the contract-pinned GLUON sim URDF to USD and write provenance."""

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess

from isaaclab.app import AppLauncher


parser = argparse.ArgumentParser(description=__doc__)
AppLauncher.add_app_launcher_args(parser)
args_cli = parser.parse_args()
args_cli.headless = True
app_launcher = AppLauncher(args_cli)
simulation_app = app_launcher.app


import isaaclab  # noqa: E402
from isaaclab.sim.converters import UrdfConverter, UrdfConverterCfg  # noqa: E402


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def checked_contract_hash(path: Path, expected: str, label: str) -> str:
    if not path.is_file():
        raise FileNotFoundError(f"{label} does not exist: {path}")
    actual = sha256_file(path)
    if actual != expected:
        raise RuntimeError(f"{label} SHA256 mismatch: actual={actual}, expected={expected}")
    return actual


def hash_output_bundle(usd_dir: Path, manifest_path: Path) -> tuple[str, list[dict[str, object]]]:
    """Hash every generated asset file, excluding the self-referential manifest."""
    digest = hashlib.sha256()
    output_files: list[dict[str, object]] = []
    for path in sorted(candidate for candidate in usd_dir.rglob("*") if candidate.is_file()):
        if path == manifest_path:
            continue
        relative_path = path.relative_to(usd_dir).as_posix()
        file_sha256 = sha256_file(path)
        size_bytes = path.stat().st_size
        output_files.append(
            {
                "relative_path": relative_path,
                "sha256": file_sha256,
                "size_bytes": size_bytes,
            }
        )
        digest.update(relative_path.encode("utf-8"))
        digest.update(b"\0")
        digest.update(file_sha256.encode("ascii"))
        digest.update(b"\0")
    return digest.hexdigest(), output_files


def normalize_converter_config(config_path: Path) -> None:
    """Remove the importer wall-clock footer; the manifest owns timestamp provenance."""
    text = config_path.read_text(encoding="utf-8")
    lines = text.splitlines()
    for index, line in enumerate(lines):
        if line.startswith("# Generated by UrdfConverter on "):
            lines[index] = "# Generated by UrdfConverter; see manifest.json for timestamp provenance."
    config_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    repo_root = Path(__file__).resolve().parents[4]
    model_root = repo_root / "sim2sim" / "robot" / "gluon"
    contract_path = model_root / "config" / "model_contract.json"
    contract = json.loads(contract_path.read_text(encoding="utf-8"))

    canonical_urdf = model_root / contract["urdf"]["relative_path"]
    sim_urdf = model_root / contract["sim_urdf"]["relative_path"]
    canonical_sha256 = checked_contract_hash(
        canonical_urdf, contract["urdf"]["sha256"], "canonical URDF"
    )
    sim_sha256 = checked_contract_hash(
        sim_urdf, contract["sim_urdf"]["sha256"], "sim URDF"
    )

    isaaclab_root = Path(isaaclab.__file__).resolve().parents[3]
    isaaclab_revision = subprocess.check_output(
        ["git", "-C", str(isaaclab_root), "rev-parse", "HEAD"],
        text=True,
    ).strip()

    usd_dir = model_root / "usd"
    usd_dir.mkdir(parents=True, exist_ok=True)
    usd_path = usd_dir / "gluon_2L6_4L3.usd"
    manifest_path = usd_dir / "manifest.json"

    importer_options = {
        "fix_base": True,
        "merge_fixed_joints": False,
        "force_usd_conversion": True,
        "make_instanceable": False,
        "joint_drive": {
            "target_type": "none",
            "stiffness": 0.0,
            "damping": 0.0,
        },
    }
    converter_cfg = UrdfConverterCfg(
        asset_path=str(sim_urdf),
        usd_dir=str(usd_dir),
        usd_file_name=usd_path.name,
        fix_base=importer_options["fix_base"],
        merge_fixed_joints=importer_options["merge_fixed_joints"],
        force_usd_conversion=importer_options["force_usd_conversion"],
        make_instanceable=importer_options["make_instanceable"],
        joint_drive=UrdfConverterCfg.JointDriveCfg(
            target_type=importer_options["joint_drive"]["target_type"],
            gains=UrdfConverterCfg.JointDriveCfg.PDGainsCfg(
                stiffness=importer_options["joint_drive"]["stiffness"],
                damping=importer_options["joint_drive"]["damping"],
            ),
        ),
    )

    converter = UrdfConverter(converter_cfg)
    generated_path = Path(converter.usd_path).resolve()
    if generated_path != usd_path.resolve():
        raise RuntimeError(f"unexpected converter output: {generated_path} != {usd_path.resolve()}")
    if not usd_path.is_file():
        raise RuntimeError(f"converter did not create output USD: {usd_path}")

    normalize_converter_config(usd_dir / "config.yaml")
    usd_sha256 = sha256_file(usd_path)
    bundle_sha256, output_files = hash_output_bundle(usd_dir, manifest_path)
    manifest = {
        "schema_version": 1,
        "model_id": contract["model_id"],
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "canonical_urdf": {
            "relative_path": canonical_urdf.relative_to(repo_root).as_posix(),
            "sha256": canonical_sha256,
        },
        "sim_urdf": {
            "relative_path": sim_urdf.relative_to(repo_root).as_posix(),
            "sha256": sim_sha256,
        },
        "output_usd": {
            "relative_path": usd_path.relative_to(repo_root).as_posix(),
            "sha256": usd_sha256,
        },
        "output_bundle": {
            "sha256": bundle_sha256,
            "files": output_files,
        },
        "isaaclab_git_revision": isaaclab_revision,
        "importer_options": importer_options,
    }
    manifest_path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    print(f"generated_usd={usd_path.relative_to(repo_root).as_posix()}", flush=True)
    print(f"usd_sha256={usd_sha256}", flush=True)
    print(f"bundle_sha256={bundle_sha256}", flush=True)
    print(f"manifest={manifest_path.relative_to(repo_root).as_posix()}", flush=True)
    print(f"isaaclab_revision={isaaclab_revision}", flush=True)
    print("GLUON_URDF_TO_USD: PASS", flush=True)


if __name__ == "__main__":
    try:
        main()
    finally:
        simulation_app.close(skip_cleanup=True)
