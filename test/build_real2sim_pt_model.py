"""DESKTOP_DRY_RUN: package URDF/STL visuals and recorded PT signal excerpts.

Geometry conversion only; no simulator, policy, network, or robot connection.
"""
from pathlib import Path
import base64
import hashlib
import json
import xml.etree.ElementTree as ET

import numpy as np
import trimesh

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "sim2sim/robot/tita/urdf/tita.urdf"
DEST = ROOT / "docs/exp/2026-10-19/real2sim2real_pt/model-data.js"


def encode(array):
    return base64.b64encode(array.tobytes()).decode("ascii")


def main():
    robot = ET.parse(SOURCE).getroot()
    meshes, sources = [], {}
    for link in robot.findall("link"):
        visual = link.find("visual")
        mesh = None if visual is None else visual.find("geometry/mesh")
        if mesh is None:
            continue
        path = (SOURCE.parent / mesh.attrib["filename"]).resolve()
        model = trimesh.load(path, process=True)
        # Merge sub-millimetre details for a small browser-only presentation asset.
        cells, reverse = np.unique(np.round(model.vertices / 0.0012), axis=0, return_inverse=True)
        positions = cells * 0.0012
        faces = reverse[model.faces]
        faces = faces[(faces[:, 0] != faces[:, 1]) & (faces[:, 1] != faces[:, 2]) & (faces[:, 0] != faces[:, 2])]
        simplified = trimesh.Trimesh(vertices=positions, faces=faces, process=False)
        assert len(positions) < 65536
        meshes.append({
            "name": link.attrib["name"],
            "positions": encode(np.round(positions * 10000).astype("<i2")),
            "normals": encode(np.round(simplified.vertex_normals * 127).astype("i1")),
            "indices": encode(faces.astype("<u2")),
        })
        sources[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
    joints = []
    for joint in robot.findall("joint"):
        child = joint.find("child").attrib["link"]
        if not any(m["name"] == child for m in meshes):
            continue
        origin = joint.find("origin")
        joints.append({
            "name": joint.attrib["name"],
            "parent": joint.find("parent").attrib["link"], "child": child,
            "xyz": [float(x) for x in origin.attrib.get("xyz", "0 0 0").split()],
            "rpy": [float(x) for x in origin.attrib.get("rpy", "0 0 0").split()],
            "axis": [float(x) for x in joint.find("axis").attrib["xyz"].split()],
        })
    sources[str(SOURCE.relative_to(ROOT))] = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    result = {"meshes": meshes, "joints": joints, "sources": sources,
              "description": "TITA repository visual meshes; 1.2 mm vertex clustering; recorded poses and illustrative scenes are specified by PT_REPLAYS and slide notes"}
    DEST.write_text("// DESKTOP_DRY_RUN: generated by test/build_real2sim_pt_model.py\nwindow.TITA_MODEL=" + json.dumps(result, separators=(",", ":")) + ";\n")
    traces = {}
    for case in ["off", "ma2"]:
        path = ROOT / f"docs/exp/2026-10-18/leg_action_filter_real_review/{case}_signals.npz"
        with np.load(path) as data:
            keep = data["rl"] & (data["t"] >= 3) & (data["t"] <= 4.4)
            traces[case] = {
                "time": np.round(data["t"][keep], 5).tolist(),
                "step": np.round((data["tau"] - data["tau_prev"])[keep, 2], 5).tolist(),
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            }
    trace_dest = DEST.with_name("evidence-data.js")
    replays = {}
    for key, folder in [("cylinder", "weakL_060_075_50000"), ("sphere", "weakL_060_075_sphere_50000")]:
        path = ROOT / f"docs/exp/2026-10-18/posma2_knee_asymmetry_sim/{folder}/signals/model_50000_k1_stand_s42.npz"
        with np.load(path) as data:
            indices = np.flatnonzero(data["t"] >= 8)[::5]
            if indices[-1] != len(data["t"]) - 1:
                indices = np.append(indices, len(data["t"]) - 1)
            rpy = np.deg2rad(data["rpy_deg"][indices].astype(float))
            rpy[:, 2] = np.unwrap(rpy[:, 2]) - rpy[0, 2]
            q = np.unwrap(data["q"].astype(float), axis=0)[indices]
            replays[key] = {"time": np.round(data["t"][indices] - 8, 5).tolist(),
                            "q": np.round(q, 6).tolist(), "rpy": np.round(rpy, 7).tolist(),
                            "z": np.round(data["position"][indices, 2], 6).tolist(),
                            "source_start_s": 8, "domain": "VALIDATION_SIM",
                            "source": str(path.relative_to(ROOT)), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    for key, day, name in [("realBefore", "2026-10-18", "flashsac_posma2_50000_202450_review"),
                           ("realAfter", "2026-10-19", "flashsac_headw0_65000_153755_review")]:
        path = ROOT / f"docs/exp/{day}/{name}/yaw_drift.npz"
        with np.load(path) as data:
            full_indices = np.flatnonzero(data["rl"] & (data["t"] >= 1) & (data["t"] <= 17))
            indices = full_indices[::2]
            if indices[-1] != full_indices[-1]:
                indices = np.append(indices, full_indices[-1])
            idle = (~data["rl"]) & (data["t"] < 0) & (np.max(np.abs(data["dq"]), axis=1) < .02)
            bias = float(np.median(data["gz"][idle]))
            gyro = data["obs"][:, :3] / .25
            assert np.max(np.abs(gyro[data["rl"], 2] - data["gz"][data["rl"]])) < 2e-6
            # Body-rate -> Euler yaw-rate; subtract each run's stationary z bias.
            rate = (gyro[:, 1] * np.sin(data["roll"]) + (gyro[:, 2] - bias) * np.cos(data["roll"])) / np.cos(data["pitch"])
            t = data["t"][full_indices]
            rate = rate[full_indices]
            yaw = np.r_[0., np.cumsum(.5 * (rate[1:] + rate[:-1]) * np.diff(t))]
            selected = np.searchsorted(full_indices, indices)
            rpy = np.column_stack([data["roll"][indices], data["pitch"][indices], yaw[selected]])
            replays[key] = {"time": np.round(data["t"][indices] - data["t"][indices[0]], 5).tolist(),
                            "q": np.round(np.unwrap(data["q"].astype(float), axis=0)[indices], 6).tolist(),
                            "rpy": np.round(rpy, 7).tolist(), "gyro_z_bias": bias,
                            "source_start_s": float(data["t"][indices[0]]), "domain": "DESKTOP_DRY_RUN",
                            "position": "display anchored; no world position reconstruction",
                            "source": str(path.relative_to(ROOT)), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    for key, case in [("filterBefore", "off"), ("filterAfter", "ma2")]:
        path = ROOT / f"docs/exp/2026-10-18/leg_action_filter_real_review/{case}_signals.npz"
        with np.load(path) as data:
            indices = np.flatnonzero(data["rl"] & (data["t"] >= 3) & (data["t"] <= 4.4))
            q = data["q"].astype(float)
            highpass = (2*q - np.roll(q, 1, axis=0) - np.roll(q, -1, axis=0)) / 4
            replays[key] = {"time": np.round(data["t"][indices] - data["t"][indices[0]], 5).tolist(),
                            "q": np.round(q[indices], 7).tolist(), "highpass": np.round(highpass[indices], 8).tolist(),
                            "mean_q": np.round(np.mean(q[indices], axis=0), 6).tolist(), "magnification": 40,
                            "source_start_s": float(data["t"][indices[0]]), "domain": "DESKTOP_DRY_RUN",
                            "filter": "q_highpass = (2*q - q_prev - q_next)/4; leg-only visualization, 40x amplitude, 0.1x time",
                            "source": str(path.relative_to(ROOT)), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    for condition in ["nominal", "low_friction", "com_forward_mass115", "com_backward_mass115"]:
        for group in [0, 1]:
            path = ROOT / f"docs/exp/2026-10-17/velocity_bias_grid_video/{condition}/group_{group}.npz"
            status_path = path.with_name(f"group_{group}_status.json")
            status = json.loads(status_path.read_text())
            with np.load(path) as data:
                ticks = data["sample_ticks"].astype(int)
                times = ticks * .02
                # 5 Hz for the first 30 s, 1 Hz thereafter. Keep both endpoints.
                keep = ((times <= 30) & (np.arange(len(times)) % 2 == 0)) | ((times > 30) & (np.arange(len(times)) % 10 == 0))
                keep[-1] = True
                ticks = ticks[keep]
                state = data["state"][ticks]
                qpos = data["qpos"][keep]
                assert qpos.shape[1] == 15
                q = np.unwrap(data["qpos"][:, 7:], axis=0)[keep]
                xy = state[:, :2] - data["state"][0, :2]
                rpy = state[:, 4:7].copy()
                rpy[:, 2] = np.unwrap(rpy[:, 2])
                replays[f"x_{condition}_{group}"] = {
                    "time": np.round(ticks * .02, 5).tolist(), "q": np.round(q, 6).tolist(),
                    "rpy": np.round(rpy, 7).tolist(), "z": np.round(qpos[:, 2], 6).tolist(),
                    "xy": np.round(xy, 7).tolist(), "velocity": np.round(state[:, 3], 7).tolist(),
                    "estimated_velocity": np.round(state[:, 8], 7).tolist(),
                    "bias": np.round(data["velocity_bias"][ticks], 7).tolist(),
                    "max_xy_m": status["max_drift_m"], "duration_s": status["duration_s"],
                    "initial_state_sha256": status["initial_physics_sha256"],
                    "checkpoint_sha256": status["checkpoint_sha256"], "onnx_sha256": status["onnx_sha256"],
                    "domain": "VALIDATION_SIM", "origin": "RL entry, includes initial 2s acquisition",
                    "source": str(path.relative_to(ROOT)), "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                }
            if group:
                assert replays[f"x_{condition}_0"]["initial_state_sha256"] == replays[f"x_{condition}_1"]["initial_state_sha256"]
    trace_dest.write_text("// DESKTOP_DRY_RUN: packaged recorded excerpts; no physics inference.\nwindow.PT_TRACES=" + json.dumps(traces, separators=(",", ":")) + ";\nwindow.PT_REPLAYS=" + json.dumps(replays, separators=(",", ":")) + ";\n")
    print(f"PASS: {len(meshes)} visual meshes, {len(joints)} joints, {len(replays)} recorded replay excerpts")


if __name__ == "__main__":
    main()
